/**
 * Two built-in pixel fonts for the text tool. They are plain tables so the result is identical on the phone and in
 * every browser. Each glyph is its rows joined by "/", with "#" for a lit pixel and "." for a dark one. Glyphs may be
 * different widths; every row of one glyph has the same width.
 */
export interface PixelFont {
  readonly id: 'small' | 'large'
  readonly label: string
  readonly height: number
  /** Dark columns between letters. */
  readonly gap: number
  /** Width of a space. */
  readonly space: number
  readonly glyphs: Readonly<Record<string, string>>
  /** Drawn for any character the font does not have, so the gap is visible instead of silent. */
  readonly placeholder: string
}

