/** Normalise the awkward table entries above into plain rows once, then validate sizes at load. */
function build(table: Record<string, string>, height: number): Record<string, string> {
  const out: Record<string, string> = {}
  for (const [ch, g] of Object.entries(table)) {
    const r = rows(g)
    while (r.length < height) r.push('.'.repeat(r[0].length))
    out[ch] = r.slice(0, height).join('/')
  }
  return out
}

export const FONTS: readonly PixelFont[] = [
  { id: 'small', label: 'Small (5 tall)', height: 5, gap: 1, space: 2, glyphs: build(SMALL, 5), placeholder: '#.#/.#./#.#/.#./#.#' },
  { id: 'large', label: 'Large (7 tall)', height: 7, gap: 1, space: 3, glyphs: build(LARGE, 7), placeholder: '#####/#...#/#...#/#...#/#...#/#...#/#####' },
]

export const fontById = (id: string): PixelFont => FONTS.find((f) => f.id === id) ?? FONTS[0]

/** The glyph rows for [ch], or the placeholder. Lower case uses the capital forms. [known] is false for placeholders. */
export function glyphFor(font: PixelFont, ch: string): { rows: string[]; known: boolean } {
  const g = font.glyphs[ch] ?? font.glyphs[ch.toUpperCase()]
  return g ? { rows: rows(g), known: true } : { rows: rows(font.placeholder), known: false }
}
