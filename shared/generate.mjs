// Generates TypeScript and Kotlin constants from the single sources in shared/.
// Usage: node shared/generate.mjs          (write files)
//        node shared/generate.mjs --check  (exit 1 if files on disk are stale)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

export const OUTPUTS = {
  ts: resolve(root, 'editor/src/generated/shared.ts'),
  kt: resolve(root, 'android/app/src/main/kotlin/com/yash/glyphstudio/generated/SharedConstants.kt'),
}

function readMask() {
  const rows = readFileSync(resolve(here, 'mask/matrix-mask.txt'), 'utf8').trim().split(/\r?\n/)
  if (rows.length !== 25 || rows.some((r) => r.length !== 25 || /[^#.]/.test(r))) {
    throw new Error('matrix-mask.txt must be 25 rows of 25 chars using only # and .')
  }
  return rows
}

export function build() {
  const c = JSON.parse(readFileSync(resolve(here, 'format/constants.json'), 'utf8'))
  const rows = readMask()
  const count = rows.join('').split('#').length - 1
  if (count !== c.ledCount) throw new Error(`mask has ${count} LEDs, constants.json says ${c.ledCount}`)
  if (rows.length !== c.matrixSize) throw new Error('matrixSize mismatch')

  const header = 'GENERATED by shared/generate.mjs from shared/mask and shared/format. Do not edit.'
  const bits = rows.map((r) => [...r].map((ch) => (ch === '#' ? '1' : '0')))

  const ts = `// ${header}
export const FORMAT_VERSION = ${c.formatVersion}
export const MATRIX_SIZE = ${c.matrixSize}
export const MATRIX_CELLS = ${c.matrixSize * c.matrixSize}
export const LED_COUNT = ${c.ledCount}
export const DEFAULT_FRAME_DURATION_MS = ${c.defaultFrameDurationMs}
export const MIN_FRAME_DURATION_MS = ${c.minFrameDurationMs}
export const MAX_FRAME_DURATION_MS = ${c.maxFrameDurationMs}
export const MAX_HISTORY = ${c.maxHistory}
export const LOOP_MODES = [${c.loopModes.map((m) => `'${m}'`).join(', ')}] as const
export type LoopMode = (typeof LOOP_MODES)[number]
export const DEFAULT_LOOP_MODE: LoopMode = '${c.defaultLoopMode}'
export const LAYER_TYPE_PIXELS = '${c.layerTypePixels}'

/** 1 where the matrix has an LED, 0 elsewhere. Row-major, index = y * MATRIX_SIZE + x. */
export const LED_MASK: readonly (0 | 1)[] = [
${bits.map((r) => `  ${r.join(', ')},`).join('\n')}
]
`

  const kt = `// ${header}
package com.yash.glyphstudio.generated

object SharedConstants {
    const val FORMAT_VERSION = ${c.formatVersion}
    const val MATRIX_SIZE = ${c.matrixSize}
    const val MATRIX_CELLS = ${c.matrixSize * c.matrixSize}
    const val LED_COUNT = ${c.ledCount}
    const val DEFAULT_FRAME_DURATION_MS = ${c.defaultFrameDurationMs}
    const val MIN_FRAME_DURATION_MS = ${c.minFrameDurationMs}
    const val MAX_FRAME_DURATION_MS = ${c.maxFrameDurationMs}
    const val MAX_HISTORY = ${c.maxHistory}
    val LOOP_MODES = listOf(${c.loopModes.map((m) => `"${m}"`).join(', ')})
    const val DEFAULT_LOOP_MODE = "${c.defaultLoopMode}"
    const val LAYER_TYPE_PIXELS = "${c.layerTypePixels}"

    /** true where the matrix has an LED. Row-major, index = y * MATRIX_SIZE + x. */
    val LED_MASK: BooleanArray = booleanArrayOf(
${bits.map((r) => `        ${r.map((b) => (b === '1' ? 'true' : 'false')).join(', ')},`).join('\n')}
    )
}
`
  return { [OUTPUTS.ts]: ts, [OUTPUTS.kt]: kt }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const files = build()
  const check = process.argv.includes('--check')
  let stale = false
  for (const [path, content] of Object.entries(files)) {
    if (check) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== content) { console.error('stale: ' + path); stale = true }
    } else {
      mkdirSync(dirname(path), { recursive: true })
      writeFileSync(path, content)
      console.log('wrote ' + path)
    }
  }
  if (check) process.exit(stale ? 1 : 0)
}
